# Escreva um algoritimo para perguntar as 4 notas de uma aluno e informar a media
print ("Digite a nota")
nota1 = int(input())
print ("Digite a segunda nota")
nota2 = int(input())
print ("Digite a terceira nota")
nota3 = int(input())
print ("Digite a quarta nota")
nota4 = int(input()) 

resultado = nota1 + nota2 + nota3 + nota4 
media = resultado / 4
print (media)
